"""Write `constraints.txt`: the pinned version of every package installed in this environment.

Does NOT edit `requirements.txt` (the direct dependencies, edited by hand) or install anything.
`scripts/check.py` fails when a `requirements.txt` pin is missing from the result. Implements
DEC-018.

Usage:
    python scripts/lock.py
"""

import subprocess
import sys
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = "# Generated by scripts/lock.py from the installed packages. Do not edit by hand.\n"


def pip_freeze() -> str:
    """Return the `pip freeze` output of the Python that runs this script."""
    result = subprocess.run(
        [sys.executable, "-m", "pip", "freeze"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
    )
    return result.stdout


def write_constraints(freeze: Callable[[], str], path: Path) -> None:
    """Write the header and the freeze output to `path`.

    Args:
        freeze: Returns the pinned package lines, one per package.
        path: The file to write, normally `constraints.txt`.
    """
    path.write_text(HEADER + freeze(), encoding="utf-8")


def main() -> int:
    """Regenerate `constraints.txt` in the project root."""
    write_constraints(pip_freeze, ROOT / "constraints.txt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
